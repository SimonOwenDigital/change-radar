#Requires -Version 7.0
<#
.SYNOPSIS
    Derives engine-backed review scenarios (tests/review/engine-scenarios.json) from the matching test cases. Offline.
.DESCRIPTION
    For every accepted fingerprint row in tests/cases/*.json, runs engine Find-Exposures with the full fingerprint and
    again with that row removed (a reject), and records how the set of exposed targets changed:
      closes  - the row's group exposed targets before and exposes none after
      widens  - after is a superset of before (or equal)
      narrows - after is a subset of before (or equal)
      equal / mixed - recorded for information
    The page parity script (Test-ReviewPageParity.mjs) checks that the page's predicted effect for each reject agrees
    with what the engine did. Regenerate after changing the engine, the rules or the cases.
#>
[CmdletBinding()]
param(
    [string]$TestsDir = (Join-Path $PSScriptRoot '..'),
    [string]$SeedDir = (Join-Path $PSScriptRoot '..' '..' 'seed'),
    [string]$OutPath = (Join-Path $PSScriptRoot 'engine-scenarios.json')
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot '..' '..' 'engine' 'ChangeRadar.Matching.psm1') -Force

$ctx = Import-MatchingContext -SeedDir $SeedDir
$base = Read-JsonFile (Join-Path $TestsDir 'base-estate.json')
$rules = @($ctx.Rules | ForEach-Object { [ordered]@{ facet = $_.signal_facet; role = $_.role } })
$scenarios = [System.Collections.Generic.List[object]]::new()

function Get-Targets($result, [string]$group) {
    @($result.exposures | Where-Object { -not $group -or $_.group -eq $group } | ForEach-Object target | Sort-Object -Unique)
}

foreach ($file in (Get-ChildItem (Join-Path $TestsDir 'cases') -Filter *.json | Sort-Object Name)) {
    $t = Read-JsonFile $file.FullName
    $estate = Merge-Estate -Base $base -Fragment $t.estate
    $assets = @(Get-AssetFingerprints -Estate $estate -Context $ctx)
    $check = Test-SignalFingerprint -Signal $t.signal -Context $ctx
    $fp = @($t.signal.fingerprint)
    $rows = @(for ($i = 0; $i -lt $fp.Count; $i++) {
        $r = $fp[$i]
        $grp = if ($r.PSObject.Properties['group'] -and $r.group) { $r.group } else { 'A' }
        $isAccepted = @($check.accepted | Where-Object { $_.group -eq $grp -and $_.facet -eq $r.facet -and $_.value -eq $r.value }).Count -gt 0
        [ordered]@{ id = "$i"; group = $grp; facet = $r.facet; value = $r.value; status = $(if ($isAccepted) { 'accepted' } else { 'rejected' }) }
    })
    $before = Find-Exposures -Signal $t.signal -Assets $assets -Estate $estate -Context $ctx
    $beforeAll = @(Get-Targets $before '')

    for ($i = 0; $i -lt $fp.Count; $i++) {
        if ($rows[$i].status -ne 'accepted') { continue }
        $sig = $t.signal | ConvertTo-Json -Depth 20 | ConvertFrom-Json -Depth 20
        $sig.fingerprint = @($fp | Where-Object { [array]::IndexOf($fp, $_) -ne $i })
        $after = Find-Exposures -Signal $sig -Assets $assets -Estate $estate -Context $ctx
        $afterAll = @(Get-Targets $after '')
        $grp = $rows[$i].group
        $beforeGroup = @(Get-Targets $before $grp)
        $afterGroup = @(Get-Targets $after $grp)
        $lost = @($beforeAll | Where-Object { $afterAll -notcontains $_ })
        $gained = @($afterAll | Where-Object { $beforeAll -notcontains $_ })
        $change = if ($beforeGroup.Count -gt 0 -and $afterGroup.Count -eq 0) { 'closes' }
                  elseif ($lost.Count -eq 0 -and $gained.Count -eq 0) { 'equal' }
                  elseif ($lost.Count -eq 0) { 'widens' }
                  elseif ($gained.Count -eq 0) { 'narrows' }
                  else { 'mixed' }
        $scenarios.Add([ordered]@{
                name = "$($t.id): reject $($rows[$i].group) $($rows[$i].facet)=$($rows[$i].value)"
                rows = $rows; target = "$i"; decision = 'reject'
                engine = [ordered]@{ change = $change; beforeGroup = $beforeGroup.Count; afterGroup = $afterGroup.Count; lost = $lost.Count; gained = $gained.Count }
            })
    }
}

[ordered]@{
    description = 'Generated by tests/review/New-EngineScenarios.ps1 from tests/cases and seed/rules.csv. Do not edit by hand.'
    rules       = $rules
    scenarios   = $scenarios
} | ConvertTo-Json -Depth 20 | Set-Content -Path $OutPath -Encoding utf8
"Wrote $($scenarios.Count) scenarios to $OutPath"
$scenarios | Group-Object { $_.engine.change } | ForEach-Object { "  $($_.Name): $($_.Count)" }

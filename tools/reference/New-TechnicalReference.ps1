#Requires -Version 7.0
<#
.SYNOPSIS
    Generates docs/reference/technical-reference.md (the low-level design) from the unpacked solutions, so it can't
    drift from what is built. Read-only: it reads files in this repository and writes one Markdown file. No tenant calls.
.DESCRIPTION
    Sources, all in this repository:
      solutions/ChangeRadarCore|Handlers|Ask/src  tables (Entity.xml), choices (OptionSets), flows (Workflows), prompts,
                                                  connection references and environment variables (Customizations.xml,
                                                  environmentvariabledefinitions), roles (Roles), generative pages
                                                  (uxagentprojects), the agent (bots)
      solutions/design/schema.json                lookup targets, and descriptions where the solution has none
      solutions/design/roles.json                 what each people role is for
    Rerun it after any change to the solutions, then rebuild the Word document.
.EXAMPLE
    pwsh -File tools/reference/New-TechnicalReference.ps1
#>
[CmdletBinding()]
param([string]$OutFile)
Set-StrictMode -Version 1.0   # XML nodes lack optional elements; stricter modes throw on those
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..' '..')).Path
if (-not $OutFile) { $OutFile = Join-Path $repo 'docs' 'reference' 'technical-reference.md' }
$sol = Join-Path $repo 'solutions'
$solutions = 'ChangeRadarCore', 'ChangeRadarHandlers', 'ChangeRadarAsk'

function Read-Xml([string]$Path) { [xml](Get-Content -LiteralPath $Path -Raw -Encoding utf8) }
# Table cells: one line, no pipes.
function Format-Cell([object]$Text) { if ($null -eq $Text) { return '' }; ("$Text" -replace '\r?\n', ' ' -replace '\|', '/' -replace '\s{2,}', ' ').Trim() }
function Get-Label($Node) {
    if (-not $Node) { return '' }
    $l = @($Node.SelectNodes('.//*[@languagecode="1033"]'))
    if ($l.Count) { return $l[0].GetAttribute('description') }
    return ''
}

$design = Get-Content (Join-Path $sol 'design' 'schema.json') -Raw | ConvertFrom-Json
$designCols = @{}
foreach ($t in $design.tables) {
    foreach ($c in $t.columns) { $designCols["crdr_$($t.name).crdr_$($c.name)"] = $c }
    $designCols["crdr_$($t.name)"] = $t
}
$rolesDesign = Get-Content (Join-Path $sol 'design' 'roles.json') -Raw | ConvertFrom-Json

$out = [System.Collections.Generic.List[string]]::new()
function Add([string]$Line = '') { $out.Add($Line) }


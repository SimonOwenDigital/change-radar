function Get-Trigger($Definition) {
    $parts = foreach ($p in $Definition.triggers.PSObject.Properties) {
        $t = $p.Value
        switch ($t.type) {
            'Recurrence' {
                $r = $t.recurrence
                $when = ''
                if ($r.PSObject.Properties['schedule']) {
                    $h = @(); $mins = @('0'); $days = @()
                    if ($r.schedule.PSObject.Properties['hours']) { $h = @($r.schedule.hours) }
                    if ($r.schedule.PSObject.Properties['minutes']) { $mins = @($r.schedule.minutes) }
                    if ($r.schedule.PSObject.Properties['weekDays']) { $days = @($r.schedule.weekDays) }
                    if ($h) { $when = ' at ' + (($h | ForEach-Object { '{0:00}:{1:00}' -f [int]$_, [int]$mins[0] }) -join ', ') }
                    if ($days) { $when = " on $($days -join ', ')$when" }
                }
                $every = if ($r.interval -eq 1) { "Every $($r.frequency.ToLower())" } else { "Every $($r.interval) $($r.frequency.ToLower())s" }
                ($every -replace 'Every day', 'Daily' -replace 'Every week', 'Weekly' -replace 'Every hour', 'Hourly') + $when
            }
            { $_ -in 'OpenApiConnectionWebhook', 'OpenApiConnection' } {
                $params = $t.inputs.parameters
                $entity = if ($params.PSObject.Properties['subscriptionRequest/entityname']) { $params.'subscriptionRequest/entityname' } else { '' }
                $msg = if ($params.PSObject.Properties['subscriptionRequest/message']) { @{ 1 = 'added'; 2 = 'deleted'; 3 = 'modified'; 4 = 'added or modified'; 5 = 'added or deleted'; 6 = 'modified or deleted'; 7 = 'added, modified or deleted' }[[int]$params.'subscriptionRequest/message'] } else { '' }
                if ($entity) { "When a ``crdr_$entity`` row is $msg" -replace 'crdr_crdr_', 'crdr_' } else { $t.inputs.host.operationId }
            }
            'Request' { 'Called by another flow or by hand' }
            default { $t.type }
        }
    }
    return ($parts -join '; ')
}
Add '| Flow | Trigger | Does | Connections and state |'
Add '|---|---|---|---|'
foreach ($s in $solutions) {
    $wf = Join-Path $sol $s 'src' 'Workflows'
    if (-not (Test-Path $wf)) { continue }
    foreach ($dx in Get-ChildItem $wf -Filter *.data.xml | Sort-Object Name) {
        $w = (Read-Xml $dx.FullName).Workflow
        $json = Get-Content (Join-Path $wf ($dx.Name -replace '\.data\.xml$', '')) -Raw | ConvertFrom-Json
        $refs = @($json.properties.connectionReferences.PSObject.Properties | ForEach-Object { "``$($_.Value.connection.connectionReferenceLogicalName)``" }) -join ', '
        $state = if ($w.StateCode -eq '1') { 'ships on' } else { 'ships off' }
        $name = $w.Name -replace '^Change Radar( handler)?:?\s*', ''
        $does = $w.Description -replace '^Change Radar handler [\w-]+( template)?:\s*', '' -replace '^Change Radar:\s*', ''
        if ($does) { $does = $does.Substring(0, 1).ToUpper() + $does.Substring(1) }
        Add ("| **{0}** ({1}) | {2} | {3} | {4}; {5} |" -f (Format-Cell $name), ($s -replace 'ChangeRadar', ''), (Format-Cell (Get-Trigger $json.properties.definition)), (Format-Cell $does), $refs, $state)
    }
}

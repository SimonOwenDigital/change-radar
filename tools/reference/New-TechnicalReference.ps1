# ----- data dictionary ------------------------------------------------------------------------------------------------
Add '## 2. Data dictionary'
Add ''
Add 'Every table is organisation-owned and prefixed ``crdr_``. Only Change Radar''s own columns are listed; each table also has the standard Dataverse columns (created by, created on, modified by, modified on, owner, status and so on).'
Add ''
$entityDir = Join-Path $sol 'ChangeRadarCore' 'src' 'Entities'
$typeNames = @{ nvarchar = 'Text'; ntext = 'Multiline text'; lookup = 'Lookup'; picklist = 'Choice'; bit = 'Yes/No'; datetime = 'Date and time'; int = 'Whole number'; decimal = 'Decimal'; primarykey = 'Unique id' }
$n = 0
foreach ($e in Get-ChildItem $entityDir -Directory | Where-Object Name -like 'crdr_*' | Sort-Object Name) {
    $x = Read-Xml (Join-Path $e.FullName 'Entity.xml')
    $ent = $x.Entity
    $display = $ent.Name.LocalizedName
    $desc = Get-Label $ent.EntityInfo.entity.Descriptions
    if (-not $desc -and $designCols[$e.Name]) { $desc = $designCols[$e.Name].description }
    $n++
    Add "### 2.$n $display (``$($e.Name)``)"
    Add ''
    if ($desc) { Add (Format-Cell $desc); Add '' }
    Add '| Column | Type | Required | Notes |'
    Add '|---|---|---|---|'
    foreach ($a in @($ent.EntityInfo.entity.attributes.attribute) | Where-Object { $_.PhysicalName -like 'crdr_*' } | Sort-Object { $_.LogicalName }) {
        if ($a.Type -eq 'primarykey') { continue }
        $d = $designCols["$($e.Name).$($a.LogicalName)"]
        $type = $typeNames[$a.Type] ?? $a.Type
        if ($a.Type -eq 'picklist' -and $a.SelectSingleNode('OptionSetName')) { $type = "Choice (``$($a.OptionSetName)``)" }
        if ($a.Type -eq 'lookup' -and $d -and $d.PSObject.Properties['target']) {
            $target = $d.target; $type = 'Lookup to ' + ($target -eq 'systemuser' ? 'User' : "``crdr_$target``")
        }
        if ($a.Type -eq 'nvarchar' -and $a.SelectSingleNode('MaxLength')) { $type = "Text ($($a.MaxLength))" }
        $notes = Get-Label $a.Descriptions
        if (-not $notes -and $d -and $d.PSObject.Properties['description']) { $notes = $d.description }
        $label = Get-Label $a.displaynames
        $req = if ($a.RequiredLevel -in 'required', 'systemrequired') { 'Yes' } else { '' }
        Add ("| ``{0}`` ({1}) | {2} | {3} | {4} |" -f $a.LogicalName, (Format-Cell $label), $type, $req, (Format-Cell $notes))
    }
    Add ''
}


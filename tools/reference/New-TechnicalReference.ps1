# ----- roles ----------------------------------------------------------------------------------------------------------
Add '## 7. Security roles'
Add ''
Add 'Privileges are at organisation level. Dataverse adds nine baseline privileges to every new role, and they are not listed: read on plug-in and SDK message metadata and on SharePoint documents and data, plus create and write on SharePoint data. They are platform defaults.'
Add ''
$baseline = 'prvReadPluginAssembly', 'prvReadPluginType', 'prvReadSdkMessage', 'prvReadSdkMessageProcessingStep', 'prvReadSdkMessageProcessingStepImage', 'prvCreateSharePointData', 'prvReadSharePointData', 'prvWriteSharePointData', 'prvReadSharePointDocument'
foreach ($f in Get-ChildItem (Join-Path $sol 'ChangeRadarCore' 'src' 'Roles') -Filter *.xml | Sort-Object Name) {
    $r = (Read-Xml $f.FullName).Role
    $privs = @($r.RolePrivileges.RolePrivilege | ForEach-Object name) | Where-Object { $_ -notin $baseline }
    $about = ($rolesDesign.roles | Where-Object name -eq $r.name | Select-Object -First 1)
    Add "### $($r.name)"
    Add ''
    Add (Format-Cell ($about ? $about.description : $r.Description))
    Add ''
    # Group by verb: prvReadcrdr_signal -> Read: crdr_signal
    Add '| Right | Tables and components |'
    Add '|---|---|'
    foreach ($g in $privs | ForEach-Object { if ($_ -match '^prv(Create|Read|Write|Delete|AppendTo|Append|Assign|Share)(.+)$') { [pscustomobject]@{ Verb = $Matches[1]; Object = $Matches[2] } } else { [pscustomobject]@{ Verb = 'Other'; Object = $_ } } } | Group-Object Verb) {
        $objects = @($g.Group.Object | Sort-Object -Unique)
        # Every Change Radar table: say so rather than list twenty names.
        $own = @($objects | Where-Object { $_ -like 'crdr_*' }); $rest = @($objects | Where-Object { $_ -notlike 'crdr_*' })
        $text = @(if ($own.Count -eq $n) { "every Change Radar table ($n)" } else { $own | ForEach-Object { "``$_``" } })
        Add ("| {0} | {1} |" -f $g.Name, (Format-Cell (($text + @($rest | ForEach-Object { "``$_``" })) -join ', ')))
    }
    Add ''
}


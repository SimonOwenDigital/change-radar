foreach ($s in $solutions) {
    $m = (Read-Xml (Join-Path $sol $s 'src' 'Other' 'Solution.xml')).ImportExportXml.SolutionManifest
    $counts = @($m.RootComponents.RootComponent) | Where-Object { $_.schemaName -ne 'SystemUser' } | Group-Object type | Sort-Object { [int]$_.Name } |
